"""Turns `terraform output -json` (stdin) + demo.properties (env) into docker/.env."""
import json
import os
import sys

out = {k: v["value"] for k, v in json.load(sys.stdin).items()}
env = {
    "DEMO_ID": out["demo_id"],
    "KAFKA_BOOTSTRAP": out["kafka_bootstrap"],
    "KAFKA_API_KEY": out["kafka_api_key"],
    "KAFKA_API_SECRET": out["kafka_api_secret"],
    "KAFKA_CLUSTER_ID": out["kafka_cluster_id"],
    "SCHEMA_REGISTRY_URL": out["schema_registry_url"],
    "SCHEMA_REGISTRY_API_KEY": out["schema_registry_api_key"],
    "SCHEMA_REGISTRY_API_SECRET": out["schema_registry_api_secret"],
    "TABLEFLOW_CATALOG_ENDPOINT": out["tableflow_catalog_endpoint"],
    "TABLEFLOW_API_KEY": out["tableflow_api_key"],
    "TABLEFLOW_API_SECRET": out["tableflow_api_secret"],
    "PCAP_REPLAY_MULTIPLIER": os.getenv("PCAP_REPLAY_MULTIPLIER", "1"),
    "SYSLOG_EVENTS_PER_SEC": os.getenv("SYSLOG_EVENTS_PER_SEC", "40"),
    "WATCHLIST_URL": os.getenv("WATCHLIST_URL", ""),
}
with open(sys.argv[1], "w") as f:
    f.write("# generated by scripts/01-provision-cloud.sh - contains secrets, do not commit\n")
    for key, value in env.items():
        f.write(f"{key}='{value}'\n")
print(f"wrote {sys.argv[1]}")
